    /**
     * Metodo per leggere il messaggio inviato dal server
     */
    private void leggiMessaggio() throws IOException {
        //lettura primo messaggio
        String rispostaServer = in.readLine();
        txaChat.append(cmbPersonalita.getSelectedItem() + ": " + rispostaServer + "\n");
    }

    /**
     * Metodo per aggiungere un messaggio alla chat
     *
     * @param messaggio
     */
    private void scriviMessaggio(String messaggio) {
        txtMessaggio.setText("");
        txaChat.append(messaggio + "\n");
    }

    /**
     * Carica e ridimensiona l'immagine selezionata a 200x200 pixel
     */
    private void mostraImmagine(String personalita) {
        try {
            String percorso = "/assets/" + personalita + ".png";
            // Caricamento immagine
            ImageIcon iconaOriginale = new ImageIcon(getClass().getResource(percorso));
            // Ridimensionamento immagine
            Image imgScalata = iconaOriginale.getImage().getScaledInstance(200, 200, Image.SCALE_SMOOTH);
            // cambio immagine
            lblImmagine.setIcon(new ImageIcon(imgScalata));
        } catch (Exception e) {
            System.err.println("Impossibile caricare l'immagine");
        }
    }

    /**
     * Metodo per cambiare la scritta del bottone ricarica
     */
    private void cambiaScrittaBottone() {
        String personalita = cmbPersonalita.getSelectedItem().toString();
        if (personalita.equals("Tassi")) {
            btnRicarica.setText("Pausa caffe'");
        } else if (personalita.equals("Buso")) {
            btnRicarica.setText("Eldego");
        } else if (personalita.equals("Aisa")) {
            btnRicarica.setText("Commentino su Parini");
        }
    }

